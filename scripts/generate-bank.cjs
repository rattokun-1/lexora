const fs=require('node:fs'),words=require('../new-word-data.js');
const q=x=>"'"+String(x).replaceAll("'","''")+"'";
const rows=words.map((w,i)=>{
 const pool=words.filter(x=>x.level===w.level&&x.meaning!==w.meaning),options=[w.meaning];
 for(let j=0;j<pool.length&&options.length<4;j++){const m=pool[(i*17+j*7)%pool.length].meaning;if(!options.includes(m))options.push(m);}
 if(options.length!==4)throw Error('Insufficient distractors: '+w.word);
 const position=i%4;[options[0],options[position]]=[options[position],options[0]];
 return `(${i+1},${w.level},${q(w.word)},${q(JSON.stringify(options))}::jsonb,${position})`;
});
fs.writeFileSync('supabase/migrations/202611030003_duel_bank.sql','-- Generated by scripts/generate-bank.cjs; private server answer bank.\ninsert into private.duel_questions(id,band,word,options,correct) values\n'+rows.join(',\n')+'\non conflict(id) do nothing;\n');
